"""Turn hardware/pcb/positions.json into hardware/cad/pcb_positions.scad.

CAD frame: X right, Y up, origin = PCB centre, seen from the front.
PCB frame: x right, y down, origin = PCB top-left, seen from the front.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(ROOT, "hardware/pcb/positions.json")))
bw, bh = d["board"]


def c(x, y):
    return [round(x - bw / 2, 3), round(bh / 2 - y, 3)]


xp = d["xiao_pads"].values()
xc = ((min(p[0] for p in xp) + max(p[0] for p in xp)) / 2, (min(p[1] for p in xp) + max(p[1] for p in xp)) / 2)
disp = d["display"]
x0, y0, x1, y1 = d["slot"]
lines = [
    "// GENERATED by tools/gen_cad_params.py from the PCB. Do not edit by hand.",
    f"pcb_w = {bw};",
    f"pcb_h = {bh};",
    f"pcb_holes = {[c(*h) for h in d['holes']]};",
    f"pcb_switches = {[c(*d['switches'][k]) for k in ('SW1', 'SW2', 'SW3')]};",
    f"pcb_display_center = {c(disp['cx'], disp['cy'])};",
    f"display_module = [{disp['w']}, {disp['h']}];",
    f"pcb_xiao_center = {c(*xc)};  // USB-C points +X",
    f"pcb_cable_slot = [{c(x0, y1)}, {c(x1, y0)}];",
]
out = os.path.join(ROOT, "hardware/cad/pcb_positions.scad")
open(out, "w").write("\n".join(lines) + "\n")
print(open(out).read())
